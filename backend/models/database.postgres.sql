create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.tickets(id) on delete restrict,
  amount_paid numeric(10,2) not null check (amount_paid > 0),
  official_receipt_number varchar(50) unique not null,
  payment_method varchar(20) not null default 'cash' check (payment_method in ('cash','gcash','maya','bank_transfer','other')),
  payment_status varchar(20) not null default 'full' check (payment_status in ('partial','full','voided')),
  payment_date date not null,
  notes text,
  recorded_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default current_timestamp,
  updated_at timestamptz not null default current_timestamp
);

create table if not exists public.disputes (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.tickets(id) on delete restrict,
  submitted_by bigint references public.users(id) on delete restrict,
  contact_name varchar(120),
  contact_email varchar(190),
  submission_source varchar(20) not null default 'internal' check (submission_source in ('internal','public')),
  reason text not null,
  status varchar(20) not null default 'submitted' check (status in ('submitted','under_review','approved','rejected','closed')),
  resolution_notes text,
  resolved_by bigint references public.users(id) on delete set null,
  resolved_at timestamptz,
  created_at timestamptz not null default current_timestamp,
  updated_at timestamptz not null default current_timestamp
);

create table if not exists public.evidence (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.tickets(id) on delete cascade,
  file_path varchar(255) not null,
