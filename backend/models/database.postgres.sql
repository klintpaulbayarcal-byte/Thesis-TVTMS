-- PostgreSQL 17 / Supabase production schema for TVTMS.
-- The Express API connects privately; browser clients must never receive the database secret.

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create or replace function private.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = current_timestamp;
  return new;
end;
$$;
revoke all on function private.set_updated_at() from public, anon, authenticated;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name varchar(100) not null,
  email varchar(100) unique not null,
  password varchar(255) not null,
  -- `driver` is retained only for legacy record integrity; the API rejects it at login.
  role varchar(30) not null default 'apprehending_officer' check (role in ('admin','apprehending_officer','driver')),
  contact_number varchar(20),
  plate_number varchar(20),
  status varchar(20) not null default 'active' check (status in ('active','inactive')),
  failed_login_attempts integer not null default 0,
  locked_until timestamptz,
  reset_token_hash varchar(64),
  reset_token_expires timestamptz,
  last_login timestamptz,
  created_at timestamptz not null default current_timestamp,
  updated_at timestamptz not null default current_timestamp
);

create table if not exists public.owners (
  id bigint generated by default as identity primary key,
  name varchar(100),
  email varchar(100),
  address text,
  contact_number varchar(20),
  created_at timestamptz not null default current_timestamp,
  updated_at timestamptz not null default current_timestamp
);

create table if not exists public.vehicles (
  id bigint generated by default as identity primary key,
  plate_number varchar(20) unique not null,
  vehicle_type varchar(20) not null check (vehicle_type in ('motorcycle','tricycle','car','truck','bus','van')),
  owner_name varchar(100),
  owner_email varchar(100),
  driver_license_number varchar(30),
  owner_address text,
  owner_id bigint references public.owners(id) on delete set null,
  created_at timestamptz not null default current_timestamp,
  updated_at timestamptz not null default current_timestamp
);

create table if not exists public.violations (
  id bigint generated by default as identity primary key,
  violation_code varchar(20) unique not null,
  violation_name varchar(150) not null,
  description text,
  penalty_amount numeric(10,2) not null check (penalty_amount >= 0),
  demerit_points integer not null default 0 check (demerit_points >= 0),
  status varchar(20) not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default current_timestamp,
  updated_at timestamptz not null default current_timestamp
);

create table if not exists public.violation_penalty_rules (
  id bigint generated by default as identity primary key,
  violation_id bigint not null references public.violations(id) on delete cascade,
  offense_count integer not null check (offense_count > 0),
  penalty_amount numeric(10,2) not null check (penalty_amount >= 0),
  is_active smallint not null default 1 check (is_active in (0,1)),
  effective_from date not null,
  effective_to date,
  created_at timestamptz not null default current_timestamp,
  updated_at timestamptz not null default current_timestamp
);

create table if not exists public.tickets (
  id bigint generated by default as identity primary key,
  ticket_number varchar(30) unique not null,
  user_id bigint not null references public.users(id) on delete restrict,
  vehicle_id bigint not null references public.vehicles(id) on delete restrict,
  violation_id bigint not null references public.violations(id) on delete restrict,
  owner_name_at_issue varchar(100),
  owner_email_at_issue varchar(100),
  owner_address_at_issue text,
  penalty_amount_at_issue numeric(10,2),
  date_issued date not null,
  time_issued time not null,
  location varchar(200),
  remarks text,
  status varchar(20) not null default 'unpaid' check (status in ('unpaid','paid','cancelled')),
  payment_date date,
  created_at timestamptz not null default current_timestamp,
  updated_at timestamptz not null default current_timestamp
);

create table if not exists public.ticket_number_sequences (
  sequence_year smallint primary key,
